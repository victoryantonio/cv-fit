"""Render a stored packet as Markdown. A pure function of the payload.

Nothing is recomputed here and nothing is judged here: if a number is not
already in the payload it does not appear. The one rule this file enforces is
the product's oldest one - the export describes, it never tells you whether to
send the application.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

VERDICT_ORDER = ("strong", "partial", "gap")
VERDICT_HEADING = {
    "strong": "Matches (verified)",
    "partial": "Partial",
    "gap": "Gaps",
}
IMPORTANCE_LABEL = {"knockout": "must have, knockout", "weight": "must have"}

DRAFT_NOTE = (
    "This cover note is a draft. Every claim in it was checked against a quote "
    "from your stored CV. Edit it before you use it."
)
UNVERIFIED_NOTE = (
    "No cover note could be verified for this analysis, so none is shown. "
    "A note is only produced when a requirement has evidence in the CV that the "
    "guard can confirm."
)
FOOTER = (
    "Generated by CV-Job Fit Analyzer. Fit numbers are computed from the stored "
    "verdicts, not written by the model."
)


def render_markdown(payload: Mapping[str, Any]) -> str:
    """Fixed section order: header, summary, requirements, evidence, note."""
    blocks = [
        _header(payload),
        _summary(payload),
        _requirements(payload),
        _evidence(payload),
        _suggestions(payload),
        _cover_note(payload),
    ]
    return "\n\n".join(block for block in blocks if block) + f"\n\n---\n\n{FOOTER}\n"


def _header(payload: Mapping[str, Any]) -> str:
    job = payload.get("job") or {}
    title = job.get("title") or "The advertised role"
    company = job.get("company")
    heading = f"# Application packet: {title}" + (f" at {company}" if company else "")
    lines = [
        heading,
        "",
        f"- Analysis: `{payload.get('id', '')}`",
        f"- Created: {payload.get('created_at', 'not recorded')}",
        f"- Model: `{payload.get('model', '')}`",
        f"- Prompt bundle: `{payload.get('prompt_bundle', '')}`",
        f"- Judgment runs per requirement: {payload.get('match_runs', 0)}",
    ]
    return "\n".join(lines)


def _summary(payload: Mapping[str, Any]) -> str:
    summary = payload.get("summary") or {}
    must = summary.get("must_have") or {}
    counts = summary.get("counts") or {}
    lines = [
        "## Fit summary",
        "",
        f"- Fit label: `{summary.get('label', 'unknown')}`",
        f"- Weighted coverage: {summary.get('coverage', 0)}%",
        "- Verdicts: " + ", ".join(f"{name} {counts.get(name, 0)}" for name in VERDICT_ORDER),
        f"- Must-have met: {must.get('met', 0)} of {must.get('total', 0)}",
    ]
    knockout = summary.get("knockout_gaps") or []
    if knockout:
        lines.append(f"- Knockout gaps: {len(knockout)}")
    flags = summary.get("constraint_flags") or []
    for flag in flags:
        lines.append(f"- Constraint: {_flag_text(flag)}")
    unstable = summary.get("unstable_count") or 0
    if unstable:
        lines.append(
            f"- Verdicts that varied between judgment runs: {unstable}. "
            "Re-run the analysis before relying on them."
        )
    return "\n".join(lines)


def _flag_text(flag: Mapping[str, Any]) -> str:
    name = flag.get("flag") or flag.get("code") or "unknown"
    detail = flag.get("detail") or flag.get("reason")
    return f"{name} ({detail})" if detail else str(name)


def _requirements(payload: Mapping[str, Any]) -> str:
    verdicts = _verdicts(payload)
    rows = [
        row
        for row in payload.get("requirements") or []
        if row.get("active") and row.get("importance") in IMPORTANCE_LABEL
    ]
    if not rows:
        return ""
    lines = ["## Must-have requirements", ""]
    for row in rows:
        verdict = verdicts.get(row.get("id"), "gap")
        lines.append(f"- [{verdict}] (priority {row.get('position', 0)}) {row.get('text', '')}")
    return "\n".join(lines)


def _evidence(payload: Mapping[str, Any]) -> str:
    verdicts = _verdicts(payload)
    quotes = {
        item.get("requirement_id"): (item.get("evidence_quote") or "").strip()
        for item in payload.get("matches") or []
    }
    sections: list[str] = []
    for verdict in VERDICT_ORDER:
        body = [
            _evidence_line(row, quotes.get(row.get("id")))
            for row in payload.get("requirements") or []
            if row.get("active") and verdicts.get(row.get("id"), "gap") == verdict
        ]
        if body:
            sections.append("\n".join([f"## {VERDICT_HEADING[verdict]}", "", *body]))
    return "\n\n".join(sections)


def _evidence_line(row: Mapping[str, Any], quote: str | None) -> str:
    label = IMPORTANCE_LABEL.get(row.get("importance", ""), "nice to have")
    text = f"- ({label}) {row.get('text', '')}"
    if quote:
        return f'{text}\n  - CV: "{quote}"'
    return text


def _suggestions(payload: Mapping[str, Any]) -> str:
    rows = payload.get("suggestions") or []
    provenance = payload.get("suggestion_provenance") or {}
    header = ["## CV suggestions", ""]
    hidden = provenance.get("hidden") or 0
    if hidden:
        header.append(f"_{hidden} suggestion(s) were withheld by the guard._")
        header.append("")
    if not rows:
        header.append("No suggestion passed the guard for this analysis.")
        return "\n".join(header)
    for row in rows:
        block = [
            f"### {row.get('type', 'edit')} in {row.get('target_section', 'the CV')}",
            "",
            f"- From: {row.get('original_text') or '(nothing yet)'}",
            f"- To: {row.get('proposed_text', '')}",
        ]
        if row.get("rationale"):
            block.append(f"- Why: {row['rationale']}")
        header.append("\n".join(block))
        header.append("")
    return "\n".join(header).rstrip()


def _cover_note(payload: Mapping[str, Any]) -> str:
    note = payload.get("cover_note")
    lines = ["## Cover note (draft)", ""]
    if isinstance(note, str):
        body: str | None = note
        reason: str | None = None
    else:
        note = note or {}
        body = note.get("text")
        reason = note.get("guard_reason")
    if not body:
        lines.append(UNVERIFIED_NOTE)
        if reason:
            lines.append("")
            lines.append(f"Reason: {reason}")
        return "\n".join(lines)
    lines.extend([body, "", DRAFT_NOTE])
    return "\n".join(lines)


def _verdicts(payload: Mapping[str, Any]) -> dict[str, str]:
    return {
        item.get("requirement_id"): item.get("verdict", "gap")
        for item in payload.get("matches") or []
    }
